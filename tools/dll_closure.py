"""Emit the full transitive DLL closure of an executable as a CMake list.

Walks imports breadth-first from the exe, resolving each name the way the loader
does for an app-local override (exe directory, then System32), and reports every
REAL DLL that is needed but not present beside the executable - plus where a
copy can be found. API sets (api-ms-win-*, ext-ms-*) are excluded: the OS
resolves those itself and there is no file to copy.
"""
from __future__ import annotations

import subprocess
from pathlib import Path

OBJDUMP = r"C:\msys64\ucrt64\bin\objdump.exe"
SYSTEM_DIRS = [Path(r"C:\Windows\System32"), Path(r"C:\Windows")]
SEARCH_DIRS = [Path(r"C:\msys64\ucrt64\bin"), Path(r"C:\Program Files\Graphviz\bin")]
EXE_DIR = Path("build-ucrt")


def imports_of(path: Path) -> list[str]:
    out = subprocess.run([OBJDUMP, "-p", str(path)], capture_output=True,
                         text=True, errors="replace").stdout
    return [l.split("DLL Name:")[1].strip() for l in out.splitlines()
            if "DLL Name:" in l]


def is_api_set(name: str) -> bool:
    n = name.lower()
    return n.startswith("api-ms-") or n.startswith("ext-ms-")


def resolve(name: str) -> Path | None:
    for d in [EXE_DIR, *SYSTEM_DIRS]:
        c = d / name
        if c.is_file():
            return c
    return None


def find_source(name: str) -> Path | None:
    for d in SEARCH_DIRS:
        c = d / name
        if c.is_file():
            return c
    return None


def main() -> None:
    seen: set[str] = set()
    queue = ["static_analyzer.exe"]
    need_copy: list[tuple[str, Path]] = []

    while queue:
        name = queue.pop(0)
        low = name.lower()
        if low in seen or is_api_set(name):
            continue
        seen.add(low)

        found = resolve(name)
        if found is None:
            src = find_source(name)
            if src is not None:
                need_copy.append((name, src))
            continue

        # Only recurse into DLLs, and skip the ones Windows always provides.
        if found.suffix.lower() != ".dll" or found.parent.name == "System32":
            if found.parent.name == "System32":
                continue
        for dep in imports_of(found):
            if not is_api_set(dep) and dep.lower() not in seen:
                queue.append(dep)

    print(f"# {len(need_copy)} DLL(s) the executable needs but does not ship")
    print(f"# generated by walking imports from build-ucrt/static_analyzer.exe")
    for name, src in sorted(need_copy):
        print(f"{name}|{src.parent}")
    print()
    by_dir: dict[str, list[str]] = {}
    for name, src in sorted(need_copy):
        by_dir.setdefault(str(src.parent), []).append(name)
    for d, names in by_dir.items():
        print(f"# from {d}")
        for n in names:
            print(f"    {n}")
        print()


if __name__ == "__main__":
    main()